'use strict';
const assert = require('node:assert/strict');
const T = require('../edit/table-model.js');
const cell = (html, spans = {}) => ({html, tag: 'TD', ...spans});
const simple = T.fromRows([[cell('А'), cell('Б'), cell('В')], [cell('Г'), cell('Д'), cell('Е')], [cell('Ж'), cell('З'), cell('И')]]);
const complete = model => { const g = T.grid(model); assert.equal(g.length, model.rows); assert.ok(g.every(row => row.length === model.columns && row.every(Boolean))); return model; };
const text = model => model.cells.map(c => c.html.replace(/<[^>]+>/g, '')).join('');
const merged = complete(T.merge(simple, 0, 4));
assert.equal(merged.cells.length, 6);
assert.equal(merged.cells[0].colSpan, 2);
assert.equal(merged.cells[0].rowSpan, 2);
assert.equal(merged.cells[0].html, '<div>А</div><div>Б</div><div>Г</div><div>Д</div>');
assert.equal(simple.cells.length, 9, 'Operations must not mutate the source');
const rowInside = complete(T.insertRow(merged, 1));
assert.equal(rowInside.cells[0].rowSpan, 3);
assert.equal(rowInside.rows, 4);
const columnInside = complete(T.insertColumn(merged, 1));
assert.equal(columnInside.cells[0].colSpan, 3);
assert.equal(columnInside.columns, 4);
const bottom = complete(T.insertRow(merged, merged.rows));
assert.equal(bottom.cells[0].rowSpan, 2, 'A boundary insertion must not extend a span');
assert.equal(bottom.cells.filter(c => c.row === 3).length, 3);
const split = complete(T.split(merged, 0));
assert.equal(split.cells.length, 9);
assert.equal(split.cells[0].html, merged.cells[0].html, 'Splitting must retain all merged text');
for (let r = 0; r <= simple.rows; r++) complete(T.insertRow(simple, r));
for (let c = 0; c <= simple.columns; c++) complete(T.insertColumn(simple, c));
const spanning = T.fromRows([[cell('А', {rowSpan: 2}), cell('Б'), cell('В')], [cell('Г', {colSpan: 2})], [cell('Д'), cell('Е'), cell('Ж')]]);
const expanded = T.rectangle(spanning, 1, 4);
assert.deepEqual([expanded.top, expanded.left, expanded.bottom, expanded.right], [0, 0, 3, 3]);
const allMerged = complete(T.merge(spanning, 1, 4));
assert.equal(allMerged.cells.length, 1);
assert.equal(text(allMerged).length, 7);
complete(T.insertColumn(allMerged, 1));
complete(T.insertRow(allMerged, 1));
complete(T.split(allMerged, allMerged.cells[0].id));
assert.equal(complete(T.fromRows([[cell('А'), cell('Б')], [cell('В')]])).cells.length, 4);
console.log('Table merge/split, rectangular span selection, row/column insertion and content preservation verified.');
